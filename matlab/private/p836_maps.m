function M = p836_maps()
%P836_MAPS Annual maps of Recommendation ITU-R P.836-6 (cached)
%   M = p836_maps() returns a structure with fields
%     p     - 1 x 18 vector of percentages of time (0.1 ... 99 %)
%     rho   - 161 x 321 x 18 surface water-vapour density (g/m^3), 1.125 deg grid,
%             rows from 90 deg N to 90 deg S, columns from 0 to 360 deg E
%     vsch  - 161 x 321 x 18 water-vapour scale height (km), same grid
%     topo  - 363 x 723 topographic altitude (km), 0.5 deg grid from 90.5 deg N
%             to 90.5 deg S and from -0.5 to 360.5 deg E
%   The file DigitalMaps_P836.mat is generated by initiate_digital_maps.m.

persistent cache
if isempty(cache)
    f = fullfile(fileparts(mfilename('fullpath')), 'DigitalMaps_P836.mat');
    if (exist(f, 'file') ~= 2)
        error(['DigitalMaps_P836.mat not found.\n' ...
               'Download Recommendation ITU-R P.836-6 (R-REC-P.836-6-201712-I!!ZIP-E.zip), extract the\n' ...
               'annual RHO_xx, VSCH_xx and TOPO_0DOT5 files to ./private/maps and run\n' ...
               'initiate_digital_maps.m.'], '');
    end
    S = load(f);
    cache = S.P836;
end
M = cache;
end
